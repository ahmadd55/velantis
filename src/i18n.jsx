const digits = "٠١٢٣٤٥٦٧٨٩";

function toArabicDigits(value) {
  return value.replace(/\d/g, (digit) => digits[digit]);
}

function translate(text, lang) {
  if (text == null) return "";
  const value = String(text);
  if (lang !== "ar") return value;
  if (ar[value]) return toArabicDigits(ar[value]);

  const found = value.match(/^(\d+) (property|properties) found$/);
  if (found) {
    const count = Number(found[1]);
    const label = count === 1 ? "تم العثور على عقار واحد" : `تم العثور على ${count} عقارات`;
    return toArabicDigits(label);
  }

  const sellers = value.match(/^(\d+) (property|properties) from verified sellers across Saudi Arabia$/);
  if (sellers) {
    const count = Number(sellers[1]);
    const label =
      count === 1
        ? "عقار واحد من بائعين موثّقين في المملكة العربية السعودية"
        : `${count} عقارات من بائعين موثّقين في المملكة العربية السعودية`;
    return toArabicDigits(label);
  }

  if (value.startsWith("SAR ")) return toArabicDigits(`ر.س ${value.slice(4)}`);

  const places = [
    "Saudi Arabia",
    "United Arab Emirates",
    "United Kingdom",
    "Diplomatic Quarter",
    "Al Muhammadiyah",
    "Khamis Mushait",
    "Al Narjis",
    "Al Yasmin",
    "Al Malqa",
    "Al Hamra",
    "Al Rawdah",
    "Al Shati",
    "Al-Ahsa",
    "Al-Qatif",
    "Riyadh",
    "Jeddah",
    "Dammam",
    "Makkah",
    "Mecca",
    "Madinah",
    "Medina",
    "Khobar",
    "Dhahran",
    "Buraidah",
    "Manhattan",
    "Florence",
    "Dubai",
    "London",
    "Nassau",
    "Najran",
    "Jubail",
    "Yanbu",
    "Sakaka",
    "Tabuk",
    "Obhur",
    "Ajyad",
    "Olaya",
    "Paris",
    "Taif",
    "Abha",
    "Jizan",
    "Hail",
    "Arar",
  ];
  let next = value;
  places.forEach((key) => {
    if (next.includes(key)) next = next.split(key).join(ar[key]);
  });
  return next === value ? value : toArabicDigits(next);
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem(STORAGE_KEY) || "en");

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang === "ar" ? "ar" : "en";
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      toggle: () => setLang((current) => (current === "ar" ? "en" : "ar")),
      t: (text) => translate(text, lang),
    }),
    [lang],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useI18n must be used within LanguageProvider");
  return value;
}
